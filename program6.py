try:
    # รับค่าจำนวนแถวจากผู้ใช้
    rows = int(input("กรอกจำนวนแถวของดาว: "))
    
    if rows <= 0:
        print("กรุณากรอกตัวเลขที่มากกว่า 0")
    else:
        # วนลูปตามจำนวนแถวที่ต้องการ
        for i in range(1, rows + 1):
            # พิมพ์ดาวตามจำนวนแถว เช่น แถวที่ 1 มี 1 ดวง, แถวที่ 2 มี 2 ดวง
            print("*" * i)

except ValueError:
    print("ข้อผิดพลาด: กรุณากรอกเฉพาะตัวเลขจำนวนเต็มเท่านั้น")